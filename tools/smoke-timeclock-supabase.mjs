import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const importSource=await readFile(new URL('../src/adapters/timeclock-import.js',import.meta.url),'utf8');
const K={people:[{personId:'P1',memberNo:'KC-1',name:'Test Person',active:true}],person(id){return this.people.find(p=>p.personId===id)}};
const context={window:{KCDP:K},console};
vm.runInNewContext(importSource,context);
K.timeclockImport.setProvider(async()=>({rows:[{sourceRecordId:'8f44b5c5',memberNo:'KC-1',date:'2026-12-04',start:'11:00',end:'15:00'}]}));
const pulled=await K.timeclockImport.pullFromTimeClock();
