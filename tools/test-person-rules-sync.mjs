import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const K={personRules:{},auth:{require:()=>{}},storage:{secret:'fixture-only'},currentUser:{role:'admin'}};
const operations=[];let next=[];let seq=0;
const secure={normalizeQueueItem:x=>({...x,operationId:'test-'+(++seq),status:'pending'}),encryptEnvelope:async x=>x,nextRetry:()=>null};
const ctx=vm.createContext({window:{KCDP:K},KCSecureSync:secure});
vm.runInContext(fs.readFileSync('src/adapters/sync.js','utf8'),ctx);
K.sync.setProvider(async r=>{if(r.action==='push'){operations.push(r.wireOperation);return {status:'ok'};}return {wireOperations:next.map(operation=>({operation})),cursor:'next'};});
next=[{operationId:'remote1',entity:'person_rules',payload:{personId:'leon',forbiddenWeekdays:[1,3]}}];
await K.sync.pull();
assert.equal(K.personRules.leon.forbiddenWeekdays.join(','),'1,3');
K.sync.enqueue({entity:'person_rules',operation:'update',payload:{personId:'leon',forbiddenWeekdays:[1,3,5]}});
next=[{operationId:'remote2',entity:'person_rules',payload:{personId:'leon',forbiddenWeekdays:[2]}}];
await K.sync.pull();
assert.equal(K.personRules.leon.forbiddenWeekdays.join(','),'1,3','Pending local rule must not be overwritten');
assert.equal(K.sync.openConflicts(),1);
await K.sync.flush();
assert.equal(operations[0].entityId,'leon','Stable person id on wire');
console.log('Regelsynchronisierung: Laden, stabile Personen-ID und Konfliktschutz geprüft.');
